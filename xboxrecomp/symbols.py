"""Name XDK library code in an XBE with XbSymbolDatabase, and list what the game calls.

usage: python symbols.py <default.xbe> <XbSymbolDatabaseCLI.exe> <out_dir>
writes <out_dir>/xdk_symbols.tsv (address, library, kind, name, call convention, params)
   and <out_dir>/d3d_calls.tsv (D3D/D3DX functions called from game code, with call counts)
"""
import collections
import os
import re
import subprocess
import sys

from capstone import x86

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import analyze  # noqa: E402

LINE = re.compile(r"^(\w{1,8}?)__(FUN|VAR|UNK)__(?:(\w+?)__)?(\w+?)(?:\((.*)\))? = 0x([0-9a-f]+)$")


def scan(xbe, cli):
    out = subprocess.run([os.path.abspath(cli), xbe, "-e"], capture_output=True, text=True, check=True).stdout
    syms = []
    for line in out.splitlines():
        m = LINE.match(line.strip())
        if not m:
            raise ValueError(f"unexpected XbSymbolDatabase line: {line}")
        lib, kind, conv, name, params, addr = m.groups()
        if kind != "FUN":  # VAR/UNK lines have no calling convention: the name took its place
            name = f"{conv}__{name}" if conv else name
            conv = ""
        syms.append((int(addr, 16), lib, kind, name, conv or "", params or ""))
    return sorted(syms)


def main(xbe, cli, out_dir):
    syms = scan(xbe, cli)
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "xdk_symbols.tsv"), "w", newline="\n") as f:
        f.write("# address\tlibrary\tkind\tname\tcall\tparams  (generated by xboxrecomp/symbols.py)\n")
        for a, lib, kind, name, conv, params in syms:
            f.write(f"{a:08x}\t{lib}\t{kind}\t{name}\t{conv}\t{params}\n")

    funcs = {a: (lib, name) for a, lib, kind, name, _, _ in syms if kind == "FUN"}
    prog = analyze.Program(xbe)
    owner = prog.run()
    # game code = functions XbSymbolDatabase did not name, outside the library sections
    lib_sections = {s.name for s in prog.code if s.name != ".text"}
    named_owner = {a for a in prog.funcs if a in funcs}

    def is_game(va):
        f = owner.get(va)
        return f is not None and f not in named_owner and prog.xbe.section(va).name not in lib_sections

    calls = collections.Counter()
    callers = collections.defaultdict(set)
    for va in owner:
        i = prog.insns[va]
        if i.id not in (x86.X86_INS_CALL, x86.X86_INS_JMP) or not is_game(va):
            continue
        op = i.operands[0]
        if op.type == x86.X86_OP_IMM and (op.imm & 0xFFFFFFFF) in funcs:
            t = op.imm & 0xFFFFFFFF
            if funcs[t][0] in ("D3D8", "D3DX8", "XGRAPHC"):
                calls[t] += 1
                callers[t].add(owner[va])
    with open(os.path.join(out_dir, "d3d_calls.tsv"), "w", newline="\n") as f:
        f.write("# address\tlibrary\tname\tcall sites\tcalling functions\n")
        for t, n in sorted(calls.items(), key=lambda kv: funcs[kv[0]][1]):
            f.write(f"{t:08x}\t{funcs[t][0]}\t{funcs[t][1]}\t{n}\t{len(callers[t])}\n")
    libs = collections.Counter(lib for _, lib, kind, *_ in syms if kind == "FUN")
    print(f"{len(syms)} symbols, functions per library: {dict(libs)}")
    print(f"game code calls {len(calls)} D3D/D3DX/XGRAPHICS functions directly")


if __name__ == "__main__":
    main(*sys.argv[1:])
